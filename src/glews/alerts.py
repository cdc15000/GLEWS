class SlackChannel(AlertChannel):
    """Slack incoming-webhook alerts using Block Kit formatting."""

    name = "slack"

    def __init__(self, webhook_url: str, timeout: int = 30) -> None:
        self.webhook_url = webhook_url
        self.timeout = timeout

    @classmethod
    def from_config(cls, cfg: dict) -> "SlackChannel | None":
        url = cfg.get("webhook_url", "")
        if not url:
            logger.warning("Slack channel: webhook_url missing; skipping")
            return None
        return cls(
            webhook_url=url,
            timeout=int(cfg.get("timeout", 30)),
        )

    @staticmethod
    def _build_payload(
        alert_level: str,
        site_name: str,
        message: str,
        details: dict[str, Any],
    ) -> dict:
        level_emoji = {
            "INFO": ":information_source:",
            "WARNING": ":warning:",
            "CRITICAL": ":rotating_light:",
        }
        emoji = level_emoji.get(alert_level, ":bell:")
        detail_lines = "\n".join(f"*{k}:* {v}" for k, v in details.items())
        return {
            "text": f"{emoji} [{alert_level}] GLEWS Alert -- {site_name}: {message}",
            "blocks": [
                {
                    "type": "header",
                    "text": {
                        "type": "plain_text",
                        "text": f"{emoji} [{alert_level}] GLEWS Alert -- {site_name}",
                    },
                },
                {
                    "type": "section",
                    "text": {"type": "mrkdwn", "text": message},
                },
                {
                    "type": "section",
                    "text": {"type": "mrkdwn", "text": detail_lines},
                },
            ],
        }

    def send(
        self,
        alert_level: str,
        site_name: str,
        message: str,
        details: dict[str, Any],
    ) -> None:
        payload = self._build_payload(alert_level, site_name, message, details)
        data = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            self.webhook_url,
            data=data,
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        urllib.request.urlopen(req, timeout=self.timeout)


# ---------------------------------------------------------------------------
# Generic webhook channel
# ---------------------------------------------------------------------------


class WebhookChannel(AlertChannel):
    """POSTs a JSON payload to an arbitrary URL."""

    name = "webhook"

    def __init__(
        self,
        url: str,
        headers: dict[str, str] | None = None,
        timeout: int = 30,
    ) -> None:
        self.url = url
        self.headers = headers or {}
        self.timeout = timeout

    @classmethod
    def from_config(cls, cfg: dict) -> "WebhookChannel | None":
        url = cfg.get("url", "")
        if not url:
            logger.warning("Webhook channel: url missing; skipping")
            return None
        return cls(
            url=url,
            headers=cfg.get("headers", {}),
            timeout=int(cfg.get("timeout", 30)),
        )

    @staticmethod
    def _build_payload(
        alert_level: str,
        site_name: str,
        message: str,
        details: dict[str, Any],
    ) -> dict:
        return {
            "alert_level": alert_level,
            "site_name": site_name,
            "message": message,
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "details": details,
        }

    def send(
        self,
        alert_level: str,
        site_name: str,
        message: str,
        details: dict[str, Any],
    ) -> None:
        payload = self._build_payload(alert_level, site_name, message, details)
        data = json.dumps(payload).encode("utf-8")
        headers = {"Content-Type": "application/json", **self.headers}
        req = urllib.request.Request(
            self.url, data=data, headers=headers, method="POST",
        )
        urllib.request.urlopen(req, timeout=self.timeout)


