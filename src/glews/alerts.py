"""
Alerting integrations for the GLEWS monitoring pipeline.

Supports email (SMTP), Slack (webhook), and generic webhook alert
channels.  Each channel is configured under the top-level ``alerts:``
key in the site YAML config.  Secrets use ``${ENV_VAR}`` expansion.

Usage::

    from glews.alerts import AlertDispatcher

    dispatcher = AlertDispatcher.from_config(site_config)
    results = dispatcher.dispatch("WARNING", "Aletsch Glacier",
                                  "Anomalous acceleration detected...",
                                  {"max_zscore": 4.2, "n_flags": 3})
"""

from __future__ import annotations

import json
import logging
import os
import re
import smtplib
import ssl
import urllib.request
import urllib.error
from abc import ABC, abstractmethod
from datetime import datetime, timezone
from email.message import EmailMessage
from typing import Any

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Environment variable expansion
# ---------------------------------------------------------------------------

_ENV_PATTERN = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}")


def expand_env_vars(value: Any) -> Any:
    """Recursively expand ``${VAR_NAME}`` references in strings, dicts,
    and lists.  Missing variables expand to the empty string."""
    if isinstance(value, str):
        return _ENV_PATTERN.sub(
            lambda m: os.environ.get(m.group(1), ""), value
        )
    if isinstance(value, dict):
        return {k: expand_env_vars(v) for k, v in value.items()}
    if isinstance(value, list):
        return [expand_env_vars(item) for item in value]
    return value


# ---------------------------------------------------------------------------
# Channel base class
# ---------------------------------------------------------------------------


class AlertChannel(ABC):
    """Abstract base for a single notification channel."""

    name: str = "base"

    @abstractmethod
    def send(
        self,
        alert_level: str,
        site_name: str,
        message: str,
        details: dict[str, Any],
    ) -> None:
        """Send an alert through this channel.  Implementations should
        raise on transient errors so the dispatcher can log them."""


# ---------------------------------------------------------------------------
# Email channel
# ---------------------------------------------------------------------------


class EmailChannel(AlertChannel):
    """SMTP-based email alerts with HTML formatting."""

    name = "email"

    def __init__(
        self,
        smtp_host: str,
        smtp_port: int = 587,
        from_addr: str = "",
        to_addrs: list[str] | None = None,
        username: str = "",
        password: str = "",
        timeout: int = 30,
    ) -> None:
        self.smtp_host = smtp_host
        self.smtp_port = smtp_port
        self.from_addr = from_addr
        self.to_addrs = to_addrs or []
        self.username = username
        self.password = password
        self.timeout = timeout

    @classmethod
    def from_config(cls, cfg: dict) -> "EmailChannel | None":
        """Build from the ``alerts.email`` config section.  Returns None
        if required fields are missing."""
        host = cfg.get("smtp_host", "")
        if not host:
            logger.warning("Email channel: smtp_host missing; skipping")
            return None
        return cls(
            smtp_host=host,
            smtp_port=int(cfg.get("smtp_port", 587)),
            from_addr=cfg.get("from", ""),
            to_addrs=cfg.get("to", []),
            username=cfg.get("username", ""),
            password=cfg.get("password", ""),
            timeout=int(cfg.get("timeout", 30)),
        )

    # -- formatting --

    @staticmethod
    def _format_html(
        alert_level: str,
        site_name: str,
        message: str,
        details: dict[str, Any],
    ) -> str:
        level_colors = {
            "INFO": "#2196F3",
            "WARNING": "#FF9800",
            "CRITICAL": "#F44336",
        }
        color = level_colors.get(alert_level, "#607D8B")
        details_rows = "".join(
            f"<tr><td style='padding:4px 8px;font-weight:bold'>{k}</td>"
            f"<td style='padding:4px 8px'>{v}</td></tr>"
            for k, v in details.items()
        )
        return (
            f"<div style='font-family:sans-serif;max-width:600px'>"
            f"<h2 style='color:{color}'>[{alert_level}] GLEWS Alert — {site_name}</h2>"
            f"<p>{message}</p>"
            f"<table style='border-collapse:collapse;width:100%'>"
            f"{details_rows}</table>"
            f"<hr><p style='font-size:0.85em;color:#888'>"
            f"Generated by GLEWS at {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}"
            f"</p></div>"
        )

    @staticmethod
    def _format_plain(
        alert_level: str,
        site_name: str,
        message: str,
        details: dict[str, Any],
    ) -> str:
        lines = [
            f"[{alert_level}] GLEWS Alert -- {site_name}",
            "",
            message,
            "",
        ]
        for k, v in details.items():
            lines.append(f"  {k}: {v}")
        return "\n".join(lines)

    # -- send --

    def send(
        self,
        alert_level: str,
        site_name: str,
        message: str,
        details: dict[str, Any],
    ) -> None:
        msg = EmailMessage()
        msg["Subject"] = f"[{alert_level}] GLEWS Alert -- {site_name}"
        msg["From"] = self.from_addr
        msg["To"] = ", ".join(self.to_addrs)

        plain = self._format_plain(alert_level, site_name, message, details)
        html = self._format_html(alert_level, site_name, message, details)

        msg.set_content(plain)
        msg.add_alternative(html, subtype="html")

        if self.smtp_port == 465:
            ctx = ssl.create_default_context()
            server = smtplib.SMTP_SSL(
                self.smtp_host, self.smtp_port,
                context=ctx, timeout=self.timeout,
            )
        else:
            server = smtplib.SMTP(
                self.smtp_host, self.smtp_port, timeout=self.timeout,
            )
            server.starttls(context=ssl.create_default_context())

        try:
            if self.username:
                server.login(self.username, self.password)
            server.send_message(msg)
        finally:
            server.quit()


