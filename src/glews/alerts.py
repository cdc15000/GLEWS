# Dispatcher
# ---------------------------------------------------------------------------

# Maps config key -> channel factory
_CHANNEL_FACTORIES: dict[str, type[AlertChannel]] = {
    "email": EmailChannel,
    "slack": SlackChannel,
    "webhook": WebhookChannel,
}


class AlertDispatcher:
    """Fan-out dispatcher: sends an alert to every configured channel,
    logging failures without crashing the monitoring loop.

    Returns per-channel success/failure so the caller can decide whether
    to mark an alert as "sent" or retry on the next cycle.
    """

    def __init__(self, channels: list[AlertChannel] | None = None) -> None:
        self.channels: list[AlertChannel] = channels or []

    @classmethod
    def from_config(cls, site_config: dict) -> "AlertDispatcher":
        """Build a dispatcher from the ``alerts:`` section of a site
        config (already env-expanded or not — we expand here)."""
        raw = site_config.get("alerts", {})
        if not raw:
            return cls()

        expanded = expand_env_vars(raw)
        channels: list[AlertChannel] = []

        for key, cfg in expanded.items():
            factory = _CHANNEL_FACTORIES.get(key)
            if factory is None:
                logger.warning("Unknown alert channel %r; skipping", key)
                continue
            if not isinstance(cfg, dict):
                logger.warning("Alert channel %r config is not a dict; skipping", key)
                continue
            channel = factory.from_config(cfg)  # type: ignore[attr-defined]
            if channel is not None:
                channels.append(channel)

        return cls(channels)

    def dispatch(
        self,
        alert_level: str,
        site_name: str,
        message: str,
        details: dict[str, Any],
    ) -> dict[str, bool]:
        """Send the alert to every configured channel.

        Returns a dict mapping channel name to success (True/False).
        An empty dict means no channels were configured (no-op).
        """
        results: dict[str, bool] = {}
        for channel in self.channels:
            try:
                channel.send(alert_level, site_name, message, details)
                results[channel.name] = True
                logger.info(
                    "Alert sent via %s for [%s] %s",
                    channel.name, site_name, alert_level,
                )
            except Exception:
                results[channel.name] = False
                logger.exception(
                    "Failed to send alert via %s for [%s]",
                    channel.name, site_name,
                )
        return results
